"""hammerc.py - finds HammerC tests and generates the code that runs them.

Usage: python hammerc.py <dir> [--nomain]

Reads every *.test.c file under <dir> (skipping <dir>/generated) and writes:
    <dir>/generated/hammer_tests.h  declarations, the test table, run_all_tests()
    <dir>/generated/hammer_main.c   main() that calls hammer_main() (not with --nomain)

Rules for a .test.c file:
    - a test is a non-static function written on one line exactly as
          void test_<name>(HammerCtx *t)
    - every other function defined in the file must be static (a helper)
    - test names must be unique across all files
Any broken rule is printed as "file:line: error: ..." and nothing is generated.
"""

import argparse
import os
import re
import sys

GENERATED_DIR = "generated"
TESTS_HEADER = "hammer_tests.h"
MAIN_FILE = "hammer_main.c"
BANNER = "/* GENERATED by hammerc.py. Do not edit; rerun the script instead. */\n"

TEST_SIGNATURE = re.compile(r"void\s+(test_\w+)\s*\(\s*HammerCtx\s*\*\s*t\s*\)")


def blank(text):
    """Replace every character except newlines with a space, so line numbers stay correct."""
    return re.sub(r"[^\n]", " ", text)


def blank_comments_strings_and_directives(text):
    """Blank out comments, string and character literals, and preprocessor lines."""
    out = []
    i = 0
    while i < len(text):
        if text.startswith("//", i):
            end = text.find("\n", i)
            end = len(text) if end == -1 else end
        elif text.startswith("/*", i):
            end = text.find("*/", i + 2)
            end = len(text) if end == -1 else end + 2
        elif text[i] in "\"'":
            end = i + 1
            while end < len(text) and text[end] not in (text[i], "\n"):
                end += 2 if text[end] == "\\" else 1
            end = min(end + 1, len(text))
        else:
            out.append(text[i])
            i += 1
            continue
        out.append(blank(text[i:end]))
        i = end

    lines = "".join(out).split("\n")
    in_directive = False
    for n, line in enumerate(lines):
        if in_directive or line.lstrip().startswith("#"):
            in_directive = line.rstrip().endswith("\\")  # directive continues on the next line
            lines[n] = blank(line)
    return "\n".join(lines)


def find_function_definitions(code):
    """Yield (head, offset) for every function definition at file level.

    The head is the text between the previous file-level ';' or '}' and the
    opening '{', for example "void test_add(HammerCtx *t)".
    """
    depth = 0
    head_start = 0
    for i, c in enumerate(code):
        if c == "{":
            if depth == 0:
                head = code[head_start:i]
                # Function heads end with ')'; struct, enum and initializer heads don't.
                if head.strip().endswith(")") and "(" in head and "=" not in head:
                    yield head, head_start
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                head_start = i + 1
        elif c == ";" and depth == 0:
            head_start = i + 1


def scan_file(path, display_path):
    """Return (tests, errors) for one .test.c file. tests is a list of (name, line)."""
    with open(path, encoding="utf-8") as f:
        code = blank_comments_strings_and_directives(f.read())

    tests = []
    errors = []
    for head, offset in find_function_definitions(code):
        offset += len(head) - len(head.lstrip())
        head = head.strip()
        line = code.count("\n", 0, offset) + 1
        words = re.findall(r"\w+", head[:head.index("(")])
        name = words[-1] if words else "?"

        if "static" in words:
            continue  # a helper
        if TEST_SIGNATURE.fullmatch(" ".join(head.split())):
            if "\n" in head:
                errors.append(f"{display_path}:{line}: error: test '{name}' must have its "
                              f"signature on one line: void {name}(HammerCtx *t)")
            else:
                tests.append((name, line))
        else:
            errors.append(f"{display_path}:{line}: error: '{name}' is not static, so it must be "
                          f"a test written as 'void test_<name>(HammerCtx *t)'. "
                          f"Make helpers static.")
    return tests, errors


def find_test_files(root):
    """Return the relative paths (with '/') of all .test.c files under root, sorted."""
    found = []
    for folder, subfolders, files in os.walk(root):
        if folder == root and GENERATED_DIR in subfolders:
            subfolders.remove(GENERATED_DIR)
        for file in files:
            if file.endswith(".test.c"):
                found.append(os.path.relpath(os.path.join(folder, file), root).replace("\\", "/"))
    return sorted(found)


def tests_header(files):
    """Text of hammer_tests.h. files is a list of (relative_path, tests)."""
    lines = [BANNER,
             "#ifndef HAMMER_TESTS_H\n",
             "#define HAMMER_TESTS_H\n",
             "\n",
             "#include \"hammerc.h\"\n"]
    for rel, tests in files:
        lines.append(f"\n/* {rel} */\n")
        for name, _ in tests:
            lines.append(f"void {name}(HammerCtx *t);\n")

    count = sum(len(tests) for _, tests in files)
    lines.append(f"\n#define HAMMER_TEST_COUNT {count}\n")
    lines.append("\nstatic const HammerTest hammer_tests[HAMMER_TEST_COUNT] = {\n")
    for rel, tests in files:
        for name, _ in tests:
            lines.append(f"    {{ \"{name}\", \"{rel}\", {name} }},\n")
    lines.append("};\n")

    lines.append("\n"
                 "/* show_passed: 1 prints every check, 0 prints only failed checks. */\n"
                 "static inline int run_all_tests_with(HammerPrintFn print, int show_passed)\n"
                 "{\n"
                 "    return hammer_run(hammer_tests, HAMMER_TEST_COUNT, print, show_passed);\n"
                 "}\n"
                 "\n"
                 "static inline int run_all_tests(void)\n"
                 "{\n"
                 "    return run_all_tests_with(hammer_print_stdout, 0);\n"
                 "}\n"
                 "\n"
                 "#endif\n")
    return "".join(lines)


def main_file():
    """Text of hammer_main.c."""
    return (BANNER +
            "#include \"hammer_tests.h\"\n"
            "\n"
            "int main(int argc, char **argv)\n"
            "{\n"
            "    return hammer_main(argc, argv, hammer_tests, HAMMER_TEST_COUNT);\n"
            "}\n")


def write_if_changed(path, text):
    """Write text to path unless the file already holds exactly that. Returns what happened."""
    if os.path.exists(path):
        with open(path, encoding="utf-8", newline="") as f:
            if f.read() == text:
                return "unchanged"
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return "written"


def main():
    parser = argparse.ArgumentParser(description="Generate the HammerC test runner for a folder of .test.c files.")
    parser.add_argument("dir", help="folder to search for .test.c files")
    parser.add_argument("--nomain", action="store_true", help=f"do not generate {MAIN_FILE}")
    args = parser.parse_args()

    if not os.path.isdir(args.dir):
        print(f"hammerc.py: error: '{args.dir}' is not a folder", file=sys.stderr)
        return 1

    files = []
    errors = []
    first_seen = {}  # test name -> "file:line" where it was first defined
    for rel in find_test_files(args.dir):
        display_path = os.path.normpath(os.path.join(args.dir, rel))
        tests, file_errors = scan_file(display_path, display_path)
        errors += file_errors
        for name, line in tests:
            where = f"{display_path}:{line}"
            if name in first_seen:
                errors.append(f"{where}: error: test '{name}' is already defined at {first_seen[name]}")
            else:
                first_seen[name] = where
        files.append((rel, tests))

    if not first_seen and not errors:
        errors.append(f"{args.dir}: error: no tests found in any .test.c file")
    if errors:
        for error in errors:
            print(error, file=sys.stderr)
        return 1

    out_dir = os.path.join(args.dir, GENERATED_DIR)
    os.makedirs(out_dir, exist_ok=True)

    header_path = os.path.join(out_dir, TESTS_HEADER)
    print(f"hammerc.py: {len(first_seen)} tests in {len(files)} files -> "
          f"{header_path} ({write_if_changed(header_path, tests_header(files))})")

    main_path = os.path.join(out_dir, MAIN_FILE)
    if args.nomain:
        if os.path.exists(main_path):
            os.remove(main_path)  # a leftover main would clash with the user's own main
            print(f"hammerc.py: removed {main_path} (--nomain)")
    else:
        print(f"hammerc.py: {main_path} ({write_if_changed(main_path, main_file())})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
